// @disk-inputs: bff/**/*.ts, ../../docs/architecture/lifecycles.generated.md
/**
 * @vitest-environment node
 */
/**
 * The declared lifecycles (ADR-0178), held three ways:
 *
 * - each means what a statechart interpreter says it means (XState is the oracle);
 * - `docs/architecture/lifecycles.generated.md` is what the code declares, so a
 *   move added in code without the reference fails here:
 *
 *     UPDATE_FIXTURES=1 bunx vitest run bff/lifecycles/registry.spec.ts
 *
 * - a `defineLifecycle` call anywhere in `bff/` is in the registry, so a new
 *   lifecycle cannot stay out of the reference.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { describe, expect, it } from 'vitest'
import { createMachine, transition } from 'xstate'
import { lifecycleDiagram } from '@/shared/lifecycle/lifecycle-diagram'
import { LIFECYCLES, type RegisteredLifecycle } from './registry'

const ROOT = process.cwd()
const REFERENCE = join(ROOT, '../../docs/architecture/lifecycles.generated.md')

function section({ lifecycle, what, where, column }: RegisteredLifecycle): string {
  const moves = lifecycle.moves.map((move) => `| \`${move.from}\` | \`${move.event}\` | \`${move.to}\` |`)
  const list = (states: readonly string[]) => (states.length > 0 ? states.map((state) => `\`${state}\``).join(', ') : 'none')
  return [
    `## ${lifecycle.id}`,
    '',
    what,
    '',
    `Stored in \`${column}\`. Declared in [\`${where}\`](../../apps/workspace/${where}).`,
    '',
    '```mermaid',
    lifecycleDiagram(lifecycle),
    '```',
    '',
    `Born as ${list(lifecycle.birthStates)}. Final: ${list(lifecycle.finalStates)}.`,
    '',
    '| From | Move | To |',
    '|---|---|---|',
    ...moves,
    '',
  ].join('\n')
}

function render(): string {
  return [
    '# Lifecycles',
    '',
    '<!-- Generated by apps/workspace/bff/lifecycles/registry.spec.ts from the declarations in code. Do not edit;',
    '     change the declaration and run: UPDATE_FIXTURES=1 bunx vitest run bff/lifecycles/registry.spec.ts -->',
    '',
    'Every record whose states and legal moves are declared in code, as the code declares them. Why they are',
    'declared this way, and which machines are not here yet: [ADR-0178](../adr/0178-lifecycles-are-declared-as-statechart-tables.md).',
    '',
    ...LIFECYCLES.map(section),
  ].join('\n')
}

function sourceFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) return sourceFiles(path)
    return /\.tsx?$/.test(entry.name) && !/\.spec\.tsx?$/.test(entry.name) ? [path] : []
  })
}

describe('the declared lifecycles', () => {
  it.each(LIFECYCLES.map((entry) => [entry.lifecycle.id, entry] as const))('%s means what a statechart says', (_id, entry) => {
    const { lifecycle } = entry
    const machine = createMachine(lifecycle.statechart())
    for (const from of lifecycle.states) {
      const at = machine.resolveState({ value: from })
      expect(at.status === 'done', `${from} is final`).toBe(lifecycle.isFinal(from))
      for (const event of lifecycle.events) {
        const [after] = transition(machine, at, { type: event })
        expect(after.value, `${from} on ${event}`).toBe(lifecycle.next(from, event) ?? from)
      }
    }
  })

  it('have unique names and name a module that declares them', () => {
    const ids = LIFECYCLES.map((entry) => entry.lifecycle.id)
    expect(new Set(ids).size).toBe(ids.length)
    for (const entry of LIFECYCLES) {
      const file = join(ROOT, entry.where)
      expect(existsSync(file), entry.where).toBe(true)
      expect(readFileSync(file, 'utf8'), entry.where).toContain(`id: '${entry.lifecycle.id}'`)
    }
  })

  it('are all in the registry', () => {
    const declaring = sourceFiles(join(ROOT, 'bff'))
      .filter((file) => /\bdefineLifecycle\s*[<(]/.test(readFileSync(file, 'utf8')))
      .map((file) => relative(ROOT, file))
      .sort()
    expect(declaring).toEqual([...new Set(LIFECYCLES.map((entry) => entry.where))].sort())
  })

  it('are drawn in the reference as the code declares them', () => {
    const rendered = render()
    if (process.env.UPDATE_FIXTURES) writeFileSync(REFERENCE, rendered)
    expect(readFileSync(REFERENCE, 'utf8')).toBe(rendered)
  })
})
