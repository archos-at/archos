// @disk-inputs: bff/agent-api/door/**
/**
 * @vitest-environment node
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { describe, expect, it } from 'vitest'

const DIR = join(process.cwd(), 'bff/agent-api/door')
const GENERATED = join(DIR, 'docs.generated.ts')

function markdownFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => (entry.isDirectory() ? markdownFiles(join(dir, entry.name)) : entry.name.endsWith('.md') ? [join(dir, entry.name)] : []))
    .sort()
}

function render(): string {
  const entries = markdownFiles(DIR).map((file) => `  ${JSON.stringify(relative(DIR, file))}: ${JSON.stringify(readFileSync(file, 'utf8'))},`)
  return (
    '// Generated by bff/agent-api/door/docs.spec.ts from the Markdown files beside it. Do not edit;\n' +
    '// edit the Markdown and run: UPDATE_FIXTURES=1 bunx vitest run bff/agent-api/door/docs.spec.ts\n' +
    '// The Markdown says {productName}; withProductName fills in the name from identity.json (ADR-0149).\n\n' +
    "import { withProductName } from '@/lib/brand'\n\n" +
    `export const DOOR_DOCS = withProductName({\n${entries.join('\n')}\n})\n\nexport type DoorDoc = keyof typeof DOOR_DOCS\n`
  )
}

describe('the door docs module', () => {
  it('embeds the Markdown files as they are', () => {
    const rendered = render()
    if (process.env.UPDATE_FIXTURES === '1') writeFileSync(GENERATED, rendered)
    expect(readFileSync(GENERATED, 'utf8')).toBe(rendered)
  })
})
