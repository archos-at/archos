from __future__ import annotations

import json
import os
import sys
from pathlib import Path

from agent.common.openrouter import PLATFORM_FIXED
from agent.common.openrouter import pin_chat_model
from agent.knowledge.permit_extraction import extract_permit_record
from agent.knowledge.permit_extraction import is_permit_decision
from agent.knowledge.permit_extraction import llm_model_name
from agent.knowledge.permit_extraction import pages_with_markers

ROOT = Path(__file__).resolve().parent.parent.parent

FIXTURES = ROOT / "apps" / "workspace" / "tests" / "fixtures" / "precedent"
OFFICE = FIXTURES / "office.json"
OUTPUT = FIXTURES / "permits.json"
COMMENT = (
    "Generated by scripts/turn_census/render_fixture_permits.py: the production pen "
    "(agent.knowledge.permit_extraction.extract_permit_record) over each Bescheid of office.json; "
    "do not edit by hand."
)


def build_extraction_llm():
    from langchain_openai import ChatOpenAI

    from agent.common.credential_resolution import resolve_llm_credential
    from agent.common.llm_factory import apply_openrouter_structured_defaults
    from agent.common.llm_factory import enforce_chat_request_contract

    cred = resolve_llm_credential(
        primary_env="BACKFILL_SUMMARY_API_KEY",
        default_base_url="https://openrouter.ai/api/v1",
        default_model=os.environ.get("DEFAULT_MODEL", "openai/gpt-6-luna"),
        base_url_env="BACKFILL_SUMMARY_BASE_URL",
        model_env="BACKFILL_SUMMARY_MODEL",
        organization_id=None,
        data_policy=PLATFORM_FIXED,
    )
    if not cred.api_key:
        raise RuntimeError(
            "No API key: set BACKFILL_SUMMARY_API_KEY (or the provider key for "
            "BACKFILL_SUMMARY_BASE_URL) to the key for the summary model configured in configs/config_*.yml."
        )
    llm = ChatOpenAI(model=cred.model, api_key=cred.api_key, base_url=cred.base_url, temperature=0, timeout=120)
    return pin_chat_model(enforce_chat_request_contract(apply_openrouter_structured_defaults(llm)), PLATFORM_FIXED)


def render(llm: object, office: dict) -> tuple[dict[str, dict], list[str]]:
    records: dict[str, dict] = {}
    missing: list[str] = []
    for project in office["projects"]:
        for document in project.get("documents") or []:
            if not is_permit_decision(document.get("tags")):
                continue
            text = pages_with_markers([(document.get("page", 1), document["text"])])
            record = extract_permit_record(text, llm, file_name=document["filename"])
            if record is None:
                missing.append(document["documentId"])
                continue
            records[document["documentId"]] = record.to_wire()
    return records, missing


def main() -> int:
    office = json.loads(OFFICE.read_text(encoding="utf-8"))
    llm = build_extraction_llm()
    records, missing = render(llm, office)
    if missing:
        print(
            f"No record for {', '.join(missing)}: nothing written; the pen failed or judged them no notice.",
            file=sys.stderr,
        )
        return 1
    document = {"$comment": COMMENT, "model": llm_model_name(llm), "records": records}
    OUTPUT.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for document_id, record in records.items():
        print(f"{document_id}: {record['kind']}, {record['authority']}, {len(record['requirements'])} requirement(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
